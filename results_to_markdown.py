"""
tools/results_to_markdown.py - Generate markdown tables from result CSVs.

Reads the benchmark tables, MTTD bridge results, and model summaries,
and prints markdown tables suitable for inclusion in the README.

Usage:
    python tools/results_to_markdown.py
"""
import csv
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS = REPO_ROOT / "results"
TABLES = RESULTS / "tables"


def csv_to_markdown(rows, headers=None):
    """Convert a list of dicts (or list of lists with headers) to a markdown table."""
    if not rows:
        return "(no data)\n"
    if headers is None:
        headers = list(rows[0].keys())
    lines = []
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        if isinstance(row, dict):
            vals = [str(row.get(h, "")) for h in headers]
        else:
            vals = [str(v) for v in row]
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines) + "\n"


def read_csv_file(path):
    """Read a CSV and return list of dicts."""
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def section_benchmark_tables():
    """Section 9.1: Synthetic benchmark tables per pattern."""
    print("### 9.1 Synthetic Workload Benchmarks\n")
    patterns = ["uniform", "linear_low", "linear_high", "random"]
    for pat in patterns:
        csv_path = TABLES / f"table_{pat}.csv"
        if not csv_path.exists():
            print(f"**{pat}**: (not found)\n")
            continue
        rows = read_csv_file(csv_path)
        print(f"**{pat.replace('_', ' ').title()}**\n")
        print(csv_to_markdown(rows))
        print()

    # Grand summary
    grand = TABLES / "grand_summary.csv"
    if grand.exists():
        print("**Grand Summary (all patterns)**\n")
        rows = read_csv_file(grand)
        print(csv_to_markdown(rows))
        print()


CRICKET = RESULTS / "cricket"
RUNS = [("Standard MTTD", "predictions_all5"),
        ("Daily reselection (--reselect-every 24)", "predictions_daily"),
        ("Hourly reselection (--reselect-every 1)", "predictions_hourly")]


def _overall(rows):
    import math
    actual = [float(r["actual"]) for r in rows]
    pred = [float(r["predicted"]) for r in rows]
    n = len(actual)
    r = math.sqrt(sum((a - p) ** 2 for a, p in zip(actual, pred)) / n)
    m = sum(abs(a - p) for a, p in zip(actual, pred)) / n
    score = 100.0 * (0.5 * r / math.sqrt(sum(a ** 2 for a in actual) / n) + 0.5 * m / (sum(actual) / n))
    names = [row["active_model"] for row in rows]
    switches = sum(1 for i in range(1, n) if names[i] != names[i - 1])
    retrains = sum(1 for row in rows if row.get("retrain_event") == "1")
    return {"Score(%)": f"{score:.2f}", "RMSE": f"{r:.2f}", "MAE": f"{m:.2f}",
            "Switches": str(switches), "Retrains": str(retrains)}


def section_mttd_results():
    """MTTD results on the cricket trace (standard, daily and hourly reselection)."""
    print("### MTTD Results (Cricket Hourly Workload)\n")
    comp = []
    for label, stem in RUNS:
        path = CRICKET / f"{stem}.csv"
        if path.exists():
            comp.append({"Run": label, **_overall(read_csv_file(path))})
    if comp:
        print(csv_to_markdown(comp, ["Run", "Score(%)", "RMSE", "MAE", "Switches", "Retrains"]))
        print()
    for label, stem in RUNS:
        summary_path = CRICKET / f"{stem}_model_summary.csv"
        if summary_path.exists():
            print(f"**Per-model summary: {label}**\n")
            print(csv_to_markdown(read_csv_file(summary_path)))
            print()


def main():
    print("# Generated Result Tables\n")
    print("_Auto-generated by `tools/results_to_markdown.py`_\n")
    print("---\n")

    section_benchmark_tables()

    print("---\n")

    section_mttd_results()


if __name__ == "__main__":
    main()
